using System.Collections.Immutable;
using System.Diagnostics;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;
using Pretender.SourceGenerator.Parser;
using Pretender.SourceGenerator.Utilities;
using Pretender.SourceGenerator.Writing;

namespace Pretender.SourceGenerator.Invocation
{
    internal record PretendMemberSpec
    {
        public required string ReturnType { get; init; }
        public required string Name { get; init; }
    }

    internal sealed record PretendMethodSpec : PretendMemberSpec
    {
        public required EquatableArray<PretendMethodParameterSpec> Parameters { get; init; }
    }

    internal sealed record PretendMethodParameterSpec
    {
        public required string Name { get; init; }
        public required string Type { get; init; }
    }

    internal sealed record PretendPropertySpec : PretendMemberSpec
    {
        public required bool HasGet { get; init; }
        public required bool HasSet { get; init; }
    }

    internal sealed record PretendSpec
    {
        public required string FilenameHint { get; init; }
        public required string TypeName { get; init; }
        public required EquatableArray<PretendMemberSpec> Members { get; init; }

        public static Result<PretendSpec> Create(INamedTypeSymbol type, CancellationToken cancellationToken)
        {
            using var memberSpecs = new ImmutableArrayBuilder<PretendMemberSpec>();
            var members = type.GetMembers();

            foreach (var member in members)
            {
                cancellationToken.ThrowIfCancellationRequested();
                if (member is IMethodSymbol method && method.MethodKind == MethodKind.Ordinary)
                {
                    memberSpecs.Add(new PretendMethodSpec
                    {
                        ReturnType = method.ReturnType.ToFullDisplayString(),
                        Name = method.Name,
                        Parameters = method.Parameters.Select(p =>
                        {
                            return new PretendMethodParameterSpec
                            {
                                Type = p.Type.ToFullDisplayString(),
                                Name = p.Name,
                            };
                        }).ToImmutableArray(),
                    });
                }
                else if (member is IPropertySymbol property)
                {
                    memberSpecs.Add(new PretendPropertySpec
                    {
                        Name = property.Name,
                        ReturnType = property.Type.ToFullDisplayString(),
                        HasGet = property.GetMethod != null,
                        HasSet = property.SetMethod != null,
                    });
                }
            }

            return new Result<PretendSpec>(new PretendSpec
            {
                FilenameHint = "",
                TypeName = "",
                Members = memberSpecs.ToImmutable(),
            }, ImmutableArray<DiagnosticInfo>.Empty);
        }

        public void Write(IndentedTextWriter writer, string name, Action<PretendMethodSpec, IndentedTextWriter> methodWriter)
        {
            writer.WriteLine("// <auto-generated/>");
            writer.WriteLine();
            writer.WriteLine($"internal class {name} : {TypeName}");
            writer.WriteLine("{");
            writer.IncreaseIndent();
            // TODO: Cache method info
            foreach (var member in Members)
            {
                if (member is PretendMethodSpec method)
                {
                    writer.WriteLine($"public {method.ReturnType} {method.Name}({string.Join(", ", method.Parameters.Select(p => $"{p.Type} {p.Name}"))})");
                    writer.WriteLine("{");
                    writer.IncreaseIndent();
                    methodWriter(method, writer);
                    writer.DecreaseIndent();
                    writer.WriteLine("}");
                }
                else if (member is PretendPropertySpec property)
                {
                    writer.WriteLine($"public {property.ReturnType} {property.Name}");
                    writer.WriteLine("{");
                    writer.IncreaseIndent();
                    if (property.HasGet)
                    {
                        writer.WriteLine("get");
                        writer.WriteLine("{");
                        writer.IncreaseIndent();
                        methodWriter(new PretendMethodSpec
                        {
                            Name = $"get_{property.Name}",
                            ReturnType = property.ReturnType,
                            Parameters = [],
                        }, writer);
                        writer.DecreaseIndent();
                        writer.WriteLine("}");
                    }
                    if (property.HasSet)
                    {
                        writer.WriteLine("set");
                        writer.WriteLine("{");
                        writer.IncreaseIndent();
                        methodWriter(new PretendMethodSpec
                        {
                            Name = $"set_{property.Name}",
                            ReturnType = "void",
                            Parameters = ImmutableArray.Create(new PretendMethodParameterSpec
                            {
                                Type = property.ReturnType,
                                Name = "value",
                            }),
                        }, writer);
                        writer.DecreaseIndent();
                        writer.WriteLine("}");
                    }
                    writer.DecreaseIndent();
                    writer.WriteLine("}");
                }
            }
        }
    }

    internal class PretendInvocation
    {
        public PretendInvocation(INamedTypeSymbol pretendType, Location location, bool fillExisting)
        {
            PretendType = pretendType;
            Location = location;
            FillExisting = fillExisting;
        }

        public INamedTypeSymbol PretendType { get; }
        public Location Location { get; }
        public bool FillExisting { get; }

        public static bool IsCandidateSyntaxNode(SyntaxNode node)
        {
            // Pretend.That<T>();
            if (node is InvocationExpressionSyntax
                {
                    Expression: MemberAccessExpressionSyntax
                    {
                        // TODO: Will this work with a using static Pretender.Pretend
                        // ...
                        // That<IInterface>();
                        Expression: IdentifierNameSyntax { Identifier.ValueText: "Pretend" },
                        Name: GenericNameSyntax { Identifier.ValueText: "That", TypeArgumentList.Arguments.Count: 1 },
                    }
                })
            {
                return true;
            }

            return false;
        }

        public static PretendInvocation? Create(GeneratorSyntaxContext context, CancellationToken cancellationToken)
        {
            Debug.Assert(IsCandidateSyntaxNode(context.Node));
            var operation = context.SemanticModel.GetOperation(context.Node, cancellationToken);
            if (operation is IInvocationOperation invocation)
            {
                cancellationToken.ThrowIfCancellationRequested();
                return CreateFromGeneric(invocation);
            }

            // TODO: Support attribute

            return null;
        }

        private static PretendInvocation? CreateFromGeneric(IInvocationOperation operation)
        {
            if (operation.TargetMethod is not IMethodSymbol
                {
                    Name: "That",
                    ContainingType: INamedTypeSymbol namedTypeSymbol,
                    TypeArguments.Length: 1,
                } || !KnownTypeSymbols.IsPretend(namedTypeSymbol))
            {
                return null;
            }

            return CreateFromTypeSymbol(
                (INamedTypeSymbol)operation.TargetMethod.TypeArguments[0], // This should be a totally safe cast
                operation.Syntax.GetLocation(),
                fillExisting: false);
        }

        private static PretendInvocation? CreateFromTypeSymbol(INamedTypeSymbol typeSymbol, Location location, bool fillExisting)
        {
            return new PretendInvocation(typeSymbol, location, fillExisting);
        }
    }
}